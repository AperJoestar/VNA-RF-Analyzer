#!/usr/bin/env python3
"""Generate synthetic VNA CSV logs so the app can be tried without lab data.

The files mimic a two-trace VNA export (Trc1 = S11, Trc2 = S21):

* ``;`` separated, optional ``#`` comment lines
* frequency in Hz, then real / imaginary parts of each trace

``vna_exp0.csv`` is the baseline (the app treats the file whose name contains ``exp0`` as the reference). Every other
file adds a resonant absorption dip whose centre frequency and depth change from file to file.

Usage::

    python scripts/generate_sample_data.py --out examples/sample_data
    python scripts/generate_sample_data.py --out my_logs --files 12 --points 401 --decimal-comma
"""
import argparse
import os

import numpy as np

HEADER = ["Freq [Hz]", "S11 Re:Trc1", "S11 Im:Trc1", "S21 Re:Trc2", "S21 Im:Trc2"]


def make_traces(freq_ghz, k, rng):
    """Return complex (S11, S21) for file number ``k`` (0 = baseline)."""
    f = np.asarray(freq_ghz, float)
    s21 = 0.85 * np.exp(-2j * np.pi * f * 0.40) * (1 + 0.02 * np.sin(2 * np.pi * f * 1.3))
    s11 = 0.35 * np.exp(-2j * np.pi * f * 0.90) * (1 + 0.05 * np.cos(2 * np.pi * f * 0.7))
    if k > 0:
        centre = 1.4 + 0.55 * k
        width = 0.22 + 0.03 * k
        depth = min(0.12 + 0.07 * k, 0.8)
        dip = 1.0 / (1.0 + ((f - centre) / width) ** 2)
        s21 = s21 * (1.0 - depth * dip)
        s11 = s11 * (1.0 - 0.6 * dip)
        noise = rng.normal(0.0, 0.002, size=(2, f.size))
        s21 = s21 + noise[0] * (1 + 0j)
        s11 = s11 + noise[1] * (1 + 0j)
    s11 = np.where(np.abs(s11) > 0.95, 0.95 * s11 / np.abs(s11), s11)  # keep SWR finite
    return s11, s21


def write_csv(path, freq_hz, s11, s21, decimal_comma=False):
    rows = ["# Synthetic VNA export generated by scripts/generate_sample_data.py", ";".join(HEADER)]
    for i in range(freq_hz.size):
        cells = [f"{freq_hz[i]:.9E}", f"{s11[i].real:.9E}", f"{s11[i].imag:.9E}",
                 f"{s21[i].real:.9E}", f"{s21[i].imag:.9E}"]
        line = ";".join(cells)
        rows.append(line.replace(".", ",") if decimal_comma else line)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(rows) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default="examples/sample_data", help="output folder (default: %(default)s)")
    ap.add_argument("--files", type=int, default=8, help="number of CSV files incl. baseline (default: %(default)s)")
    ap.add_argument("--points", type=int, default=201, help="sweep points per file (default: %(default)s)")
    ap.add_argument("--start", type=float, default=1.0, help="start frequency, GHz (default: %(default)s)")
    ap.add_argument("--stop", type=float, default=6.0, help="stop frequency, GHz (default: %(default)s)")
    ap.add_argument("--seed", type=int, default=42, help="random seed (default: %(default)s)")
    ap.add_argument("--decimal-comma", action="store_true", help="write 1,5 instead of 1.5 (EU style)")
    args = ap.parse_args(argv)

    rng = np.random.default_rng(args.seed)
    freq_ghz = np.linspace(args.start, args.stop, args.points)
    os.makedirs(args.out, exist_ok=True)
    for k in range(args.files):
        s11, s21 = make_traces(freq_ghz, k, rng)
        path = os.path.join(args.out, f"vna_exp{k}.csv")
        write_csv(path, freq_ghz * 1e9, s11, s21, decimal_comma=args.decimal_comma)
        print("wrote", path)


if __name__ == "__main__":
    main()
